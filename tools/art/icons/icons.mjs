// Builds client/src/art/sheets/icons.js (40x40 framed icons, 2x density). Run: node tools/art/icons/icons.mjs
// HD icons (hd.mjs) are drawn natively at 40x40 (36x36 art box). Every other icon is still the 20x20 legacy glyph, 2x nearest-neighbour
// upscaled into a native 40x40 frame (see upscale()), until it is redrawn in hd.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Glyph, PalBuilder, HD_S } from './kit.mjs';
import { ABILITIES } from './abilities.mjs';
import { ABILITIES_NH } from './abilities_newheroes.mjs';   // Pudge / Mirana / Rubick
import { ITEMS } from './items.mjs';
import { HD } from './hd.mjs';
import { TRAINER } from './extract_trainer.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
// Trainer icon frames reused as-is (posterized official-style art, same 20x20 frame): our key -> trainer key
export const REUSE = {};   // nothing reused any more: every ability/item icon is hand-drawn

const pb = new PalBuilder();
const frames = {};
const draw = (def) => { const [theme, fn] = def; const g = new Glyph(theme); fn(g); return g.render(); };
const drawHD = (def) => { const [theme, fn] = def; const g = new Glyph(theme, HD_S); fn(g); return g.render(); };
// 20x20 legacy frame -> 40x40: the 16x16 art box is doubled into the middle of the 36x36 art box, the 2px ring around it is plain themed
// background, and the 1px outline + 1px bevel are redrawn natively (so the frame is the same thickness as on HD icons).
function upscale(def) {
  const [theme, fn] = def; const g = new Glyph(theme); fn(g); const a = g.render();
  const bgOnly = new Glyph(theme).render(), e = new Glyph(theme, HD_S).render();
  const out = e.map(r => r.slice());   // native HD frame + flat bands
  for (let y = 2; y < HD_S - 2; y++) for (let x = 2; x < HD_S - 2; x++) {
    const bx = x - 4, by = y - 4;
    if (bx >= 0 && by >= 0 && bx < 32 && by < 32) out[y][x] = a[2 + (by >> 1)][2 + (bx >> 1)];
    else out[y][x] = bgOnly[2 + Math.max(0, Math.min(15, Math.floor(by / 2)))][2 + Math.max(0, Math.min(15, Math.floor(bx / 2)))];
  }
  return out;
}

for (const [k, def] of Object.entries({ ...ABILITIES, ...ABILITIES_NH, ...ITEMS })) if (!REUSE[k]) frames[k] = pb.rows(HD[k] ? drawHD(HD[k]) : upscale(def));
for (const [k, tk] of Object.entries(REUSE)) {
  const rows = TRAINER.frames[tk];
  frames[k] = rows.map(r => [...r].map(c => (c === '.' ? '.' : pb.ch(TRAINER.pal[c]))).join(''));
}
frames.invoker_empty1 = frames.empty; frames.invoker_empty2 = frames.empty;
frames.rubick_empty1 = frames.empty; frames.rubick_empty2 = frames.empty;   // Rubick stolen-spell slots while empty

// stable key order: invoker, heroes, items, misc
const order = [];
const push = k => { if (frames[k] && !order.includes(k)) order.push(k); };
['invoker_quas', 'invoker_wex', 'invoker_exort', 'invoker_empty1', 'invoker_empty2', 'invoker_invoke',
  'invoker_cold_snap', 'invoker_ghost_walk', 'invoker_ice_wall', 'invoker_emp', 'invoker_tornado', 'invoker_alacrity', 'invoker_sun_strike', 'invoker_forge_spirit', 'invoker_chaos_meteor', 'invoker_deafening_blast'].forEach(push);
Object.keys(ABILITIES).forEach(push); Object.keys(ABILITIES_NH).forEach(push); ['rubick_empty1', 'rubick_empty2'].forEach(push); Object.keys(ITEMS).filter(k => k.startsWith('item_')).forEach(push);
['gold', 'lock', 'empty', 'attr_str', 'attr_agi', 'attr_int', 'attr_all', 'skillpoint'].forEach(push);
Object.keys(frames).forEach(push);

const q = s => JSON.stringify(s);
let out = `// GENERATED by tools/art/icons/icons.mjs -- do not hand-edit. 40x40 framed icons at 2x density (1px dark outline, 1px bevel, 36x36 art area).\n`;
out += `// Keys: ability keys exactly as in shared/heroes.js (invoker_empty1/2 = empty slot), item keys exactly as docs/DECISIONS.md (item_*), plus gold, lock, empty, attr_str/agi/int/all, skillpoint, item_recipe.\n`;
out += `// Every icon is hand-drawn with the kit in tools/art/icons (no trainer art reused).\n`;
out += `export default {\n  pal: {\n${Object.entries(pb.pal).map(([c, h]) => `    ${q(c)}: ${q(h)}`).join(',\n')}\n  },\n  anchor: [0, 0],\n  frames: {\n`;
out += order.map(k => `    ${q(k)}: [\n${frames[k].map(r => `      ${q(r)}`).join(',\n')}\n    ]`).join(',\n');
out += `\n  }\n};\n`;
const file = path.join(ROOT, 'client/src/art/sheets/icons.js');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log('wrote', file, order.length + ' icons', Object.keys(pb.pal).length + ' colours');
