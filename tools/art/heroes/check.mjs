// Validate hero sheets. node tools/art/heroes/check.mjs [name...]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSheet } from '../png.mjs';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const SH = path.join(ROOT, 'client/src/art/sheets');
const ALL = ['sven', 'lina', 'lion', 'crystal_maiden', 'axe', 'sniper', 'zuus', 'drow_ranger', 'juggernaut'];
const names = process.argv.slice(2).length ? process.argv.slice(2) : ALL;
const ANIMS = { idle: 4, walk: 4, attack: 3, cast: 3, stunned: 2 };
let bad = 0;
for (const n of names) {
  const err = [];
  const file = path.join(SH, n + '.js');
  if (!fs.existsSync(file)) { console.log(`FAIL ${n}: missing`); bad++; continue; }
  const src = fs.readFileSync(file, 'utf8');
  if (!src.startsWith(`// GENERATED by tools/art/heroes/${n}.mjs`)) err.push('header');
  const S = loadSheet(n);
  const { pal, frames, anchor, emit = {} } = S;
  for (const k of Object.keys(emit)) if (!pal[k]) err.push(`emit key ${k} not in pal`);
  const need = ['portrait'];
  for (const [a, c] of Object.entries(ANIMS)) for (const d of (S.px > 1 ? ['s', 'se', 'e', 'ne', 'n'] : 'sne')) for (let i = 0; i < c; i++) need.push(`${a}_${d}_${i}`);
  for (const k of need) if (!frames[k]) err.push(`missing ${k}`);
  let W0 = 0, H0 = 0;
  for (const [k, rows] of Object.entries(frames)) {
    const w = rows[0].length;
    if (rows.some(r => r.length !== w)) err.push(`${k}: ragged`);
    for (const r of rows) for (const ch of r) if (ch !== '.' && !pal[ch]) { err.push(`${k}: char ${ch} not in pal`); break; }
    if (k === 'idle_s_0') { W0 = w; H0 = rows.length; }
    if (k !== 'portrait' && !/^(death|portrait)/.test(k) && rows.every(r => /^\.*$/.test(r))) err.push(`${k}: empty`);
  }
  if (!anchor || anchor[0] < 0 || anchor[0] >= W0 || anchor[1] < 0 || anchor[1] >= H0) err.push('anchor out of bounds');
  else {
    const rows = frames.idle_s_0; let last = -1; rows.forEach((r, y) => { if (/[^.]/.test(r)) last = y; });
    if (anchor[1] < last) err.push(`anchor row ${anchor[1]} above last row ${last}`);
  }
  // edge clipping: any opaque pixel on last/first col or row 0 for gameplay frames
  const clip = [];
  for (const [k, rows] of Object.entries(frames)) {
    if (k === 'portrait') continue;
    const w = rows[0].length;
    if (/[^.]/.test(rows[0]) || rows.some(r => r[0] !== '.' || r[w - 1] !== '.')) clip.push(k);
  }
  if (clip.length) err.push(`touches edge: ${clip.join(' ')}`);
  const cnt = Object.keys(frames).length;
  if (err.length) { bad++; console.log(`FAIL ${n} (${W0}x${H0}, ${cnt} frames):\n  ` + err.join('\n  ')); }
  else console.log(`ok   ${n} ${W0}x${H0} anchor ${anchor} frames ${cnt}`);
}
process.exit(bad ? 1 : 0);
