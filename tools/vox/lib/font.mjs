export const textW = (s, k = 1) => Math.max(0, String(s).length * 4 * k - k);

export function drawText(C, x0, y0, s, color = '#c8d0e8', k = 1) {
  const c = hex(color);
  [...String(s).toUpperCase()].forEach((ch, n) => {
    const g = G[ch] || G['*'];
    for (let r = 0; r < 5; r++) for (let q = 0; q < 3; q++) if (g[r * 3 + q] === '1') {
      for (let yy = 0; yy < k; yy++) for (let xx = 0; xx < k; xx++) {
        const X = x0 + n * 4 * k + q * k + xx, Y = y0 + r * k + yy;
        if (X < 0 || Y < 0 || X >= C.W || Y >= C.H) continue;
        const i = (Y * C.W + X) * 4; C.px[i] = c[0]; C.px[i + 1] = c[1]; C.px[i + 2] = c[2]; C.px[i + 3] = 255;
      }
    }
  });
}
